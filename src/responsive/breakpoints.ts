/**
 * The breakpoints module (optional) and the `_fluid.scss` helper.
 *
 * - Breakpoints: SCSS variables and a media query map for a breakpoint mixin, plus CSS custom
 *   properties, from the token config's `breakpoints`.
 * - `_fluid.scss`: a Sass function and mixin for one-off fluid values in component styles, using
 *   the Utopia viewport, so they follow the same range as the type and space scales.
 */
import path from 'node:path'

import type { UtopiaViewport } from '../fluid/utopia'

/** One breakpoint: the width it starts at, its variable suffix and a label for the comments. */
export interface Breakpoint {
  minWidth: number
  /** `$bp-min-width-<suffix>`, `--bp-max-width-<suffix>`. */
  suffix: string
  label: string
}

export interface BreakpointsConfig {
  /** px per rem. */
  rootFontSize: number
  /** Smallest first. The keys name the media queries in the map: `md`, `md_lt`, `md_o`. */
  sizes: Readonly<Record<string, Breakpoint>>
  layout: { pageMinContentWidth: number; pageMaxWidth: number }
  /** The SCSS map of media queries the breakpoint mixin reads, without `$`. */
  mapName: string
  /** Where the SCSS variables and the CSS custom properties go, from the project root. */
  output: { scss: string; css: string }
}

export interface FluidToolConfig {
  /** Where `_fluid.scss` goes, from the project root. */
  output: string
}

export const GENERATED_HEADER =
  '// Auto-generated by s58-tokens from design-tokens/tokens.config.ts - do not edit'

const formatPx = (value: number) => `${value}px`

function formatRem(value: number, rootFontSize: number): string {
  return `${Number((value / rootFontSize).toFixed(4))}rem`
}

const minVar = (b: Breakpoint) => `$bp-min-width-${b.suffix}`
const maxVar = (b: Breakpoint) => `$bp-max-width-${b.suffix}`

function rangeLines(name: string, b: Breakpoint, next?: Breakpoint): string[] {
  const lines = [
    `  // ${b.label}: >=${b.minWidth}px`,
    `  ${name}: 'screen and (min-width: #{${minVar(b)}})',`,
    `  // Below ${b.label.toLowerCase()}: <${b.minWidth}px`,
    `  ${name}_lt: 'screen and (max-width: #{${maxVar(b)}})',`,
  ]
  if (next) {
    lines.push(
      `  // Only ${b.label.toLowerCase()}: >=${b.minWidth}px, <${next.minWidth}px`,
      `  ${name}_o: 'screen and (min-width: #{${minVar(b)}}) and (max-width: #{${maxVar(next)}})',`,
    )
  }
  return lines
}

export function generateBreakpointsScss(
  config: BreakpointsConfig,
  viewport: UtopiaViewport,
): string {
  const entries = Object.entries(config.sizes)
  const lines = [GENERATED_HEADER]
  for (const [, b] of entries) {
    lines.push(`${minVar(b)}: ${formatPx(b.minWidth)};`)
    lines.push(`${maxVar(b)}: ${minVar(b)} - 1;`)
  }
  const { pageMinContentWidth, pageMaxWidth } = config.layout
  lines.push(
    '',
    `$page-min-content-width: ${formatPx(pageMinContentWidth)};`,
    `$page-max-width: ${formatRem(pageMaxWidth, config.rootFontSize)}; // ${pageMaxWidth}px`,
    `$utopia-min-width: ${viewport.minWidth};`,
    `$utopia-max-width: ${viewport.maxWidth};`,
    `$utopia-relative-to: '${viewport.relativeTo}';`,
    '',
    '// For use with the ../tools/breakpoint mixin.',
    '// n    = target breakpoints at and above this',
    '// n_lt = target breakpoints less than this',
    '// n_o  = target only this breakpoint range',
    `$${config.mapName}: (`,
  )
  entries.forEach(([name, b], index) => {
    const next = entries[index + 1]?.[1]
    lines.push(...rangeLines(name, b, next))
    if (next) lines.push('')
  })
  lines.push(');', '')
  return lines.join('\n')
}

export function generateBreakpointsCssScss(config: BreakpointsConfig): string {
  const scss = path.posix.relative(
    path.posix.dirname(config.output.css),
    config.output.scss.replace(/(^|\/)_([^/]+)\.scss$/, '$1$2'),
  )
  const sizes = Object.values(config.sizes)
  const lines = [GENERATED_HEADER, `@use '${scss}' as *;`, '', ':root {', '  /* Breakpoints */']
  for (const b of sizes) lines.push(`  --bp-max-width-${b.suffix}: #{${maxVar(b)}};`)
  for (const b of sizes) lines.push(`  --bp-min-width-${b.suffix}: #{${minVar(b)}};`)
  lines.push(
    '',
    '  /* Layout widths */',
    '  --page-min-content-width: #{$page-min-content-width};',
    '  --page-max-width: #{$page-max-width};',
    '}',
    '',
  )
  return lines.join('\n')
}

/** `utopiaScss` is the path to utopia-core-scss's `src/utopia`, relative to the output file. */
export function generateFluidToolScss(viewport: UtopiaViewport, utopiaScss: string): string {
  return [
    GENERATED_HEADER,
    "@use 'sass:string';",
    `@use '${utopiaScss}' as utopia;`,
    '',
    `$utopia-min-width: ${viewport.minWidth} !default;`,
    `$utopia-max-width: ${viewport.maxWidth} !default;`,
    `$utopia-relative-to: '${viewport.relativeTo}' !default;`,
    '',
    '// Fluid clamp helper for component/module SCSS.',
    '//',
    '// Use the function when you need a value:',
    '//   gap: fluid-clamp(16, 48);',
    '//   padding-block: fluid-clamp(24, 96);',
    '//',
    '// Use the mixin when you want to pass the property name:',
    '//   @include fluid-clamp(padding-inline, 24, 96);',
    '//',
    '// Numbers are interpreted the same way as Utopia token generation:',
    `// - viewport range defaults to ${viewport.minWidth}px -> ${viewport.maxWidth}px`,
    '// - output defaults to rem endpoints and vw interpolation',
    '// - pass $use-px: true for px endpoints, e.g. fluid-clamp(16, 48, $use-px: true)',
    '// - override $min-width/$max-width only for one-off component-specific ranges',
    '@function fluid-clamp(',
    '  $min-size,',
    '  $max-size,',
    '  $min-width: $utopia-min-width,',
    '  $max-width: $utopia-max-width,',
    '  $relative-to: $utopia-relative-to,',
    '  $use-px: false',
    ') {',
    '  @return string.unquote(',
    '    utopia.calculateClamp(',
    '      (',
    "        'minWidth': $min-width,",
    "        'maxWidth': $max-width,",
    "        'minSize': $min-size,",
    "        'maxSize': $max-size,",
    "        'relativeTo': $relative-to,",
    "        'usePx': $use-px,",
    '      )',
    '    )',
    '  );',
    '}',
    '',
    '@mixin fluid-clamp(',
    '  $property,',
    '  $min-size,',
    '  $max-size,',
    '  $min-width: $utopia-min-width,',
    '  $max-width: $utopia-max-width,',
    '  $relative-to: $utopia-relative-to,',
    '  $use-px: false',
    ') {',
    '  #{$property}: fluid-clamp($min-size, $max-size, $min-width, $max-width, $relative-to, $use-px);',
    '}',
    '',
  ].join('\n')
}

/** The path from a file in the project to utopia-core-scss's `src/utopia`, for `@use`. */
export function utopiaScssFrom(output: string): string {
  return path.posix.relative(path.posix.dirname(output), 'node_modules/utopia-core-scss/src/utopia')
}
