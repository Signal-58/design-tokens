/**
 * Helpers for the code that runs inside Figma. Each module has a `*.figma.js` file exporting one
 * async function; it is inlined, with `export ` removed, into the use_figma script or the plugin.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

/** The source of a `*.figma.js` file in this folder, ready to inline. */
export function inlineFigmaFunction(file: string): string {
  return fs
    .readFileSync(path.join(__dirname, file), 'utf8')
    .replace(/^export async function/m, 'async function')
    .trim()
}

/**
 * The Figma file a script or plugin may touch (`file-guard.figma.js`). `fileName` is the fallback
 * for when Figma doesn't give the plugin the file's key.
 */
export interface FileGuard {
  project: string
  fileKey: string
  fileName?: string
}

/**
 * A use_figma script: the guard, the function, its spec, and a call. Top-level await and return,
 * no imports. The guard throws before anything is read or changed, so use_figma discards the run.
 */
export function figmaScript(
  file: string,
  fn: string,
  spec: unknown,
  dryRun: boolean,
  guard: FileGuard,
): string {
  return [
    `// Generated by s58-tokens figma script. Runs ${fn} from ${file}.`,
    inlineFigmaFunction('file-guard.figma.js'),
    '',
    inlineFigmaFunction(file),
    '',
    `const FILE = await checkFile(${JSON.stringify(guard)})`,
    'if (!FILE.ok) throw new Error(FILE.message)',
    `const SPEC = ${JSON.stringify(spec)}`,
    `return await ${fn}(SPEC, ${dryRun})`,
    '',
  ].join('\n')
}
