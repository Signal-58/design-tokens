/**
 * Helpers for the code that runs inside Figma. Each module has a `*.figma.js` file exporting one
 * async function; it is inlined, with `export ` removed, into the use_figma script or the plugin.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

/** The source of a `*.figma.js` file in this folder, ready to inline. */
export function inlineFigmaFunction(file: string): string {
  return fs
    .readFileSync(path.join(__dirname, file), 'utf8')
    .replace(/^export async function/m, 'async function')
    .trim()
}

/** A use_figma script: the function, its spec, and a call. Top-level await and return, no imports. */
export function figmaScript(file: string, fn: string, spec: unknown, dryRun: boolean): string {
  return [
    `// Generated by s58-tokens figma script. Runs ${fn} from ${file}.`,
    inlineFigmaFunction(file),
    '',
    `const SPEC = ${JSON.stringify(spec)}`,
    `return await ${fn}(SPEC, ${dryRun})`,
    '',
  ].join('\n')
}
