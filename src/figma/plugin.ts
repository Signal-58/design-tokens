/**
 * code.js for a project's tokens development plugin (`s58-tokens figma plugin`). On open it dry-runs
 * every module and shows one report; Apply runs them for real: variables first, then text styles.
 * The plugin only knows the config as it was when this ran, so the UI shows the build time.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

import { inlineFigmaFunction } from './inline'
import type { TextStyleSpec } from './text-styles'
import type { VariablesSpec } from './variables'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

export interface PluginSpecs {
  variables?: VariablesSpec
  textStyles?: TextStyleSpec
}

export function buildFigmaPlugin(specs: PluginSpecs, builtAt: Date = new Date()): string {
  const ui = fs.readFileSync(path.join(__dirname, 'plugin-ui.html'), 'utf8')
  return [
    '// Generated by `s58-tokens figma plugin` from design-tokens/. Do not edit: change the config and rebuild.',
    inlineFigmaFunction('apply-variables.figma.js'),
    '',
    inlineFigmaFunction('apply-text-styles.figma.js'),
    '',
    `const SPECS = ${JSON.stringify(specs)}`,
    `const BUILT_AT = ${JSON.stringify(builtAt.toISOString())}`,
    `const UI = ${JSON.stringify(ui)}`,
    '',
    'async function run(dryRun) {',
    '  try {',
    '    const reports = {}',
    '    if (SPECS.variables) reports.variables = await applyVariables(SPECS.variables, dryRun)',
    '    if (SPECS.textStyles) reports.textStyles = await applyTextStyles(SPECS.textStyles, dryRun)',
    "    figma.ui.postMessage({ type: 'report', dryRun, reports, builtAt: BUILT_AT })",
    '  } catch (error) {',
    "    figma.ui.postMessage({ type: 'error', message: String((error && error.message) || error) })",
    '  }',
    '}',
    '',
    'figma.showUI(UI, { width: 440, height: 560, themeColors: true })',
    'figma.ui.onmessage = (msg) => {',
    "  if (msg.type === 'apply') return run(false)",
    "  if (msg.type === 'close') figma.closePlugin()",
    '}',
    'run(true)',
    '',
  ].join('\n')
}
