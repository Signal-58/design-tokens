/**
 * code.js for a project's tokens development plugin (`s58-tokens figma plugin`). On open it dry-runs
 * every module and shows one report; Apply runs them for real: variables first, then colour
 * scopes, then code syntax, then text styles. Export reads the semantics Figma owns into the file the build reads.
 * Both also compare those semantics with the committed file (diff-semantics.figma.js), so the
 * report says when Figma has changes to pull.
 * The plugin only knows the config as it was when this ran, so the UI shows the build time and the
 * package version. Before either, the file guard checks it's the project's Figma file.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

import type { CodeSyntaxSpec } from './code-syntax'
import type { ColourScopesSpec } from './colour-scopes'
import type { DiffSpec } from './diff'
import type { ExportSpec } from './semantics'
import { inlineFigmaFunction, type FileGuard } from './inline'
import type { TextStyleSpec } from './text-styles'
import type { VariablesSpec } from './variables'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

export interface PluginSpecs {
  variables?: VariablesSpec
  colourScopes?: ColourScopesSpec
  /** Names Figma's semantics that have no code syntax, by the project's rules. */
  codeSyntax?: CodeSyntaxSpec
  textStyles?: TextStyleSpec
  /** The Export button: what to leave out (the variables the plugin writes). */
  export?: ExportSpec
  /** The dry run's comparison with the committed pulled file, when there is one. */
  diff?: DiffSpec
}

/** This package's version, from its package.json (two folders up from src/figma and dist/figma). */
export function packageVersion(): string {
  const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', '..', 'package.json'), 'utf8'))
  return String(pkg.version)
}

export function buildFigmaPlugin(
  specs: PluginSpecs,
  guard: FileGuard,
  builtAt: Date = new Date(),
): string {
  const ui = fs.readFileSync(path.join(__dirname, 'plugin-ui.html'), 'utf8')
  return [
    '// Generated by `s58-tokens figma plugin` from design-tokens/. Do not edit: change the config and rebuild.',
    inlineFigmaFunction('file-guard.figma.js'),
    '',
    inlineFigmaFunction('apply-variables.figma.js'),
    '',
    inlineFigmaFunction('apply-colour-scopes.figma.js'),
    '',
    inlineFigmaFunction('apply-code-syntax.figma.js'),
    '',
    inlineFigmaFunction('apply-text-styles.figma.js'),
    '',
    inlineFigmaFunction('export-semantics.figma.js'),
    '',
    inlineFigmaFunction('diff-semantics.figma.js'),
    '',
    `const SPECS = ${JSON.stringify(specs)}`,
    `const GUARD = ${JSON.stringify(guard)}`,
    `const BUILT_AT = ${JSON.stringify(builtAt.toISOString())}`,
    `const VERSION = ${JSON.stringify(packageVersion())}`,
    `const UI = ${JSON.stringify(ui)}`,
    '',
    'async function run(dryRun) {',
    '  try {',
    '    // Checked again before Apply, in case the plugin was left open while switching files.',
    '    const file = await checkFile(GUARD)',
    "    if (!file.ok) return figma.ui.postMessage({ type: 'blocked', message: file.message })",
    '    const reports = {}',
    '    if (SPECS.variables) reports.variables = await applyVariables(SPECS.variables, dryRun)',
    '    if (SPECS.colourScopes) reports.colourScopes = await applyColourScopes(SPECS.colourScopes, dryRun)',
    '    if (SPECS.codeSyntax) reports.codeSyntax = await applyCodeSyntax(SPECS.codeSyntax, dryRun)',
    '    // What the variables module creates, so the text styles dry run works on a blank file.',
    '    const planned = SPECS.variables',
    "      ? SPECS.variables.collections.flatMap((c) => c.variables.map((v) => c.name + '\\u0000' + v.name))",
    '      : []',
    '    if (SPECS.textStyles) reports.textStyles = await applyTextStyles(SPECS.textStyles, dryRun, planned)',
    "    // What Export would change in the committed file. Reads only; Apply doesn't pull.",
    '    if (SPECS.diff) reports.semantics = await diffSemantics(SPECS.diff)',
    "    figma.ui.postMessage({ type: 'report', dryRun, reports, builtAt: BUILT_AT, version: VERSION, checkedBy: file.by })",
    '  } catch (error) {',
    "    figma.ui.postMessage({ type: 'error', message: String((error && error.message) || error) })",
    '  }',
    '}',
    '',
    '// The Export button: the semantics Figma owns, as the file the build reads. Reads only.',
    'async function exportFile() {',
    '  try {',
    '    const file = await checkFile(GUARD)',
    "    if (!file.ok) return figma.ui.postMessage({ type: 'blocked', message: file.message })",
    "    if (!SPECS.export) throw new Error('This plugin was built without the export.')",
    '    const { tokens, report } = await exportSemantics(SPECS.export)',
    "    figma.ui.postMessage({ type: 'exported', json: JSON.stringify(tokens, null, 2) + '\\n', report })",
    '  } catch (error) {',
    "    figma.ui.postMessage({ type: 'error', message: String((error && error.message) || error) })",
    '  }',
    '}',
    '',
    'figma.showUI(UI, { width: 440, height: 560, themeColors: true })',
    'figma.ui.onmessage = (msg) => {',
    "  if (msg.type === 'apply') return run(false)",
    "  if (msg.type === 'export') return exportFile()",
    "  if (msg.type === 'close') figma.closePlugin()",
    '}',
    'run(true)',
    '',
  ].join('\n')
}
